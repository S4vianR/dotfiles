#!/bin/sh

# Inicializar las claves de pacman
pacman-key --init

# Descargar y configurar pacman.conf personalizado
curl -o /tmp/pacman.conf https://raw.githubusercontent.com/S4vianR/dotfiles/refs/heads/main/package-managers/pacman.conf
rm /etc/pacman.conf
mv /tmp/pacman.conf /etc

# Crear mirrorlist con tu mirror primero y otros como respaldo
echo "Configurando mirrorlist con tu mirror personalizado..."
{
    echo "##"
    echo "## Arch Linux repository mirrorlist"
    echo "## Generated by arch.sh installer"
    echo "##"
    echo ""
    echo "## Mirror personalizado - Prioridad máxima"
    echo "Server = https://arch.rubr.xyz/\$repo/os/\$arch"
    echo ""
} > /etc/pacman.d/mirrorlist

# Forzar actualización de la base de datos
echo "Actualizando base de datos de paquetes..."
pacman -Syy

# Instalar archinstall
echo "Instalando archinstall..."
pacman -S --noconfirm archinstall

echo ""
echo "✅ Instalación completada!"
echo "✅ archinstall está listo para usar"
echo "✅ Tu mirror personalizado (https://arch.rubr.xyz/) ha sido configurado como prioritario"
echo "✅ ¡Buena suerte con tu instalación! :)"
